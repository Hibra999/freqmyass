import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel: 'msedge', headless: true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765/?view=advanced');
await page.getByRole('button',{name:'Connect research engine',exact:true}).click();
await page.getByRole('status').filter({hasText:'Research engine connected.'}).waitFor({timeout:60000});
await page.getByRole('link',{name:'Backtest explorer',exact:false}).click();
await page.waitForURL('**/backtest');
await page.waitForTimeout(1500);
assert((await page.locator('body').innerText()).includes('Backtest'));
assert(await page.locator('.sidebar svg path').count() > 0, 'Navigation icons are missing');
await page.screenshot({path:'../.runtime/native-backtest.png',fullPage:true});
await page.goto('http://127.0.0.1:8765/?view=trading');
await page.getByRole('heading', {name:'You are in control.'}).waitFor({timeout:60000});
assert((await page.locator('body').innerText()).includes('Simulated funds'));
assert((await page.locator('body').innerText()).includes('stopped'));
await page.getByRole('button', {name:'Start bot',exact:true}).waitFor();
await page.screenshot({path:'../.runtime/trading-desk.png',fullPage:true});
await browser.close();
assert.deepEqual(errors,[]);
console.log('Research and stopped simulation desk: authentication, native controls, navigation and icons passed.');
